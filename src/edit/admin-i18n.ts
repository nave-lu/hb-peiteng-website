export type AdminKey = keyof typeof de;
const DICT = { de, fr };
/** Text in der Sprache des Admins; {n}/{e} werden ersetzt */
export const A = (k: AdminKey, vars: Record<string, string | number> = {}) =>
  DICT[adminLang][k].replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ''));

