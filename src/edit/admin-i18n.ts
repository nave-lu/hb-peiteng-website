/* Sprache des Admins: Deutsch oder Französisch (umschaltbar in der Leiste, merkt sich der Browser).
 * Die Inhalte der Seite bleiben in ihrer Sprache (LB/FR/DE); nur die Bedienung wechselt. */
export type AdminLang = 'de' | 'fr';

const KEY = 'hbp-admin-lang';
const read = (): AdminLang | null => { try { const v = localStorage.getItem(KEY); return v === 'fr' || v === 'de' ? v : null; } catch { return null; } };
export let adminLang: AdminLang = read() ?? (document.documentElement.lang === 'fr' ? 'fr' : 'de');
export function setAdminLang(l: AdminLang) {
  adminLang = l;
  try { localStorage.setItem(KEY, l); } catch { /* egal */ }
}

